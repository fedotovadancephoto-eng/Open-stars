import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source=fs.readFileSync(new URL('../src/admin/reportPaymentSheets.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {buildPaymentSheets}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const children=[{id:'c',fullName:'Тест',branch:'НЛО',groupName:'Базовый'}];
const payments=[{id:'p',child_id:'c',month:'2026-09-01',amount:0}];
const charges=[{child_id:'c',month:'2026-09-01',expected_amount:6000}];
const base={payment_id:'p',child_id:'c',received_at:'2026-09-10T18:00:00Z'};
const receipts=[{...base,amount:4000,payment_method:'bank_transfer'},{...base,amount:2000,payment_method:'cash'},{...base,amount:1000,payment_method:'cash',refunded_at:'2026-09-11T01:00:00Z'},{...base,amount:999,payment_method:'cash',voided_at:'2026-09-11'}];
const filters={branch:'',groupName:'',childId:'',fromDate:'2026-09-11',toDate:'2026-09-11'};
const sheets=buildPaymentSheets(children,payments,receipts,charges,filters);
const row=sheets[0].rows[0];
assert.equal(row.received,6000);assert.equal(row.cash,2000);assert.equal(row.noncash,4000);assert.equal(row.refunded,1000);assert.equal(row.remaining,0);
assert.equal(sheets[1].rows.length,3);assert.equal(sheets[1].rows[0].date,'2026-09-11');
assert.equal(buildPaymentSheets([],payments,receipts,charges,filters)[1].rows.length,0);
assert.equal(buildPaymentSheets(children,payments,receipts,[],filters)[0].rows[0].remaining,null);
